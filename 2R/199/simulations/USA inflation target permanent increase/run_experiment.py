"""Run this G-Cubed simulation: An increase in the USA inflation target.

Purpose
-------
Apply the selected simulation design to a solved-model baseline and generate
results for the baseline and every successive simulation layer.

Archetype
---------
Standard experiment. One client-selected design is projected once; no parameter
optimisation or external-projection fixed-point iteration is performed.

Client-owned inputs
-------------------
The configuration constants below select the model, solved baseline,
design, chartpacks, documentation, derivations, and run behaviour.

Setup-generated inputs
----------------------
The selected design, standard simulation layers, and chartpacks may be
generated by setup or maintained manually. setup.py and setup.yaml are not
required to run this command.

Outputs
-------
The results folder receives run.log, projection data, deviations, and HTML
reports. Solving a missing model also writes the configured solved model.

Workflow
--------
Create results and logging, load or solve the model, create derivations,
construct the baseline, run the selected design once, and report every layer.

Run
---
Run ``python run_experiment.py`` from any working directory.

Rerun and mutation behaviour
----------------------------
Existing solved-model state is reused. A missing model is solved only when
the options below authorise it. Reporting replaces same-named result files
but does not regenerate or modify designs, layers, or chartpacks.
"""

from __future__ import annotations

import logging
from pathlib import Path
import pickle
import sys

from joblib import dump, load

from gcubed import configure_logging
from gcubed.derivations import create_derivations
from gcubed.linearisation.solved_model import SolvedModel
from gcubed.model import Model
from gcubed.model_configuration import ModelConfiguration
from gcubed.projections.baseline_projections import BaselineProjections
from gcubed.reporting import generate_all_simulation_results
from gcubed.runners.simulation_runner import SimulationRunner

# =============================================================================
# CLIENT CONFIGURATION
# =============================================================================

# Model resources
SCRIPT_FOLDER: Path = Path(__file__).resolve().parent
MODEL_FOLDER: Path = SCRIPT_FOLDER.parent.parent
MODEL_CONFIGURATION_FILE: Path = MODEL_FOLDER / "model_configuration.yaml"
BASELINE_RESULTS_FOLDER_NAME: str = "baseline"
SOLVED_MODEL_FILE_NAME: str = "solved_model.joblib"

# Experiment resources
# Select one design to run. The design owns its complete ordered layer list.
EXPERIMENT_DESIGN_FILE_NAME: str = "design.yaml"
# Every chartpack is applied to the same completed projections in order.
CHARTPACK_FILES: tuple[str, ...] = ("chartpack.yaml",)
DOCUMENTATION_FILE: Path = SCRIPT_FOLDER / "documentation.md"
REPORT_TEMPLATE_FILE: Path = MODEL_FOLDER / "templates" / "chart-template-2.0.html"

# Results
MODEL_RESULTS_FOLDER: Path = (
    MODEL_FOLDER.parent.parent
    / "results"
    / MODEL_FOLDER.parent.name
    / MODEL_FOLDER.name
)
RESULTS_FOLDER: Path = MODEL_RESULTS_FOLDER / SCRIPT_FOLDER.name

# Run options
# True permits an interactive solve prompt when the solved model is missing.
ASK_TO_SOLVE_MODEL_IF_MISSING: bool = True
# True solves automatically when missing. Solving can be expensive and writes
# SOLVED_MODEL_FILE_NAME in the selected baseline results folder.
SOLVE_MODEL_IF_MISSING: bool = True
# True opens each generated report in a browser; False only writes results.
SHOW_FINAL_RESULTS: bool = True

# Derived variables
# These names create one derivation collection shared by simulation and
# reporting. An empty tuple disables derived-variable calculation.
DERIVATION_NAMES: tuple[str, ...] = ("GDPRGROWTH",)


def main() -> None:
    """Run the complete standard experiment in execution order."""
    RESULTS_FOLDER.mkdir(parents=True, exist_ok=True)
    configure_logging(folder=RESULTS_FOLDER)
    logger = logging.getLogger(__name__)

    logger.info("Loading the model configuration")
    model_configuration = load_model_configuration()

    logger.info("Loading or solving the model")
    solved_model = load_or_solve_model(model_configuration)

    logger.info("Creating derived variables")
    derivations = create_derivations(DERIVATION_NAMES)

    logger.info("Constructing baseline projections")
    baseline_projections = BaselineProjections(solved_model=solved_model)

    logger.info("Loading the selected design and running the experiment")
    all_projections = run_design(baseline_projections, derivations)

    logger.info("Persisting projections and generating results")
    for chartpack_file_name in CHARTPACK_FILES:
        generate_all_simulation_results(
            chartpack_path=SCRIPT_FOLDER / chartpack_file_name,
            documentation_path=DOCUMENTATION_FILE,
            template_path=REPORT_TEMPLATE_FILE,
            results_directory_path=RESULTS_FOLDER,
            all_projections=all_projections,
            derivations=derivations,
            show_final_results=SHOW_FINAL_RESULTS,
        )

    logger.info("Experiment run completed successfully")


# =============================================================================
# MODEL LOADING OR SOLVING
# =============================================================================


def load_model_configuration() -> ModelConfiguration:
    """Load the selected model configuration and local model Python path."""
    if not MODEL_CONFIGURATION_FILE.is_file():
        raise FileNotFoundError(
            f"Model configuration not found: {MODEL_CONFIGURATION_FILE}"
        )
    configuration = ModelConfiguration(configuration_file=MODEL_CONFIGURATION_FILE)
    python_folder = configuration.python_directory
    if str(python_folder) not in sys.path:
        sys.path.insert(0, str(python_folder))
    return configuration


def load_or_solve_model(
    model_configuration: ModelConfiguration,
) -> SolvedModel:
    """Load the baseline model or solve it under the visible policy."""
    solved_model_file = (
        MODEL_RESULTS_FOLDER / BASELINE_RESULTS_FOLDER_NAME / SOLVED_MODEL_FILE_NAME
    )
    if solved_model_file.is_file():
        logging.getLogger(__name__).warning(
            "Loading the solved model from %s", solved_model_file
        )
        with solved_model_file.open("rb") as file:
            return load(file)

    should_solve = SOLVE_MODEL_IF_MISSING
    if not should_solve and ASK_TO_SOLVE_MODEL_IF_MISSING and sys.stdin.isatty():
        response = input(
            f"Solved model not found at {solved_model_file}. "
            "Solve the model now and save it there? [y/N] "
        )
        should_solve = response.strip().lower() in {"y", "yes"}
    if not should_solve:
        raise FileNotFoundError(
            f"Solved model not found at {solved_model_file}. Run the "
            "baseline first, set SOLVE_MODEL_IF_MISSING=True, or enable "
            "ASK_TO_SOLVE_MODEL_IF_MISSING in this run script."
        )

    solved_model_file.parent.mkdir(parents=True, exist_ok=True)
    solved_model = SolvedModel(model=Model(configuration=model_configuration))
    with solved_model_file.open("wb") as file:
        logging.getLogger(__name__).info("Serialising the solved model")
        dump(
            solved_model,
            file,
            compress=("zlib", 0),
            protocol=pickle.HIGHEST_PROTOCOL,
        )
    return solved_model


# =============================================================================
# BASELINE CONSTRUCTION
# =============================================================================

# Baseline construction is intentionally visible in main(). The model has
# already been loaded or solved before BaselineProjections is instantiated.


# =============================================================================
# EXPERIMENT-SPECIFIC IMPLEMENTATION
# =============================================================================


def run_design(
    baseline_projections: BaselineProjections,
    derivations: object,
) -> list[object]:
    """Run the selected design and return every resulting projection layer."""
    design_path = SCRIPT_FOLDER / EXPERIMENT_DESIGN_FILE_NAME
    if not design_path.is_file():
        raise FileNotFoundError(f"Experiment design not found: {design_path}")

    runner = SimulationRunner(
        baseline_projections=baseline_projections,
        experiment_design_file=(f"{SCRIPT_FOLDER.name}/{EXPERIMENT_DESIGN_FILE_NAME}"),
        derivations=derivations,
    )
    runner.run()
    return list(runner.all_projections)


if __name__ == "__main__":
    main()
